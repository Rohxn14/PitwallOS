"""
Pace laps (src/analytics/laps.py) — Phase 2 step 1

Which laps show a car's racing pace, and why every other lap does not.

Silver keeps every lap and flags it (rule 3); each consumer picks its own laps. This module is
the pick for measuring PACE, which steps 3 and 4 measure from: laps where the driver was racing
under green, with a lap time the timing trusts. Every lap of the race gets exactly one
`pace_status`: `pace`, or the FIRST reason in EXCLUSION_ORDER that applies. So the exclusion
ledger adds up to the number of laps and no lap is counted twice. The order puts the state of
the race first (lap 1, red flag, safety car, VSC, yellow), then the driver's own pit laps, then
data problems, then the outlier rule: a stop made under the safety car counts as "safety car".

The reasons before `outlier` are Silver's `is_clean_lap` split into its parts, and a check
enforces that the two agree. Rohan's design note (2026-10-12): nothing else is excluded.
Wet-tyre laps stay and are grouped by compound instead (inters and wets get their own pace);
deleted laps stay and keep their `is_deleted` flag.

The outlier rule (Rohan: an odd lap is much slower than anything tyre wear or dirty air explains,
which is 1-3 s at most):
  * reference = the median of the clean lap and up to 2 clean neighbours on each side (5 laps),
    from the same tyre run (the laps between two pit passages) on the same compound. A rolling
    median follows the slow drift through a stint (fuel burning off, tyres wearing, the track
    rubbering in), so a worn tyre is never "odd": only a sudden jump is.
  * outlier = more than OUTLIER_THRESHOLD_SEC slower than its reference. Never faster: a lap is
    not odd for being quick (bad timing is `is_accurate`'s job).
  * a tyre run with fewer than MIN_REFERENCE_LAPS clean laps has no reference. Its laps stay pace
    laps, unchecked (`outlier_checked` False), and are counted.
  Measured on the 66,049 clean laps of 2023-2025 before building: the median dry stint spreads
  1.1 s (10-90 %). One median for the whole stint would have flagged 147 laps at the very end
  of stints, the tyre wear step 3 measures; the rolling median does not.

The rolling median uses later laps as well as earlier ones. That is fine here: Phase 2 describes
finished races. Gold (model input) could never do it (rule 5: no leakage).

Pace by compound is RAW: not fuel-corrected. Hards usually run later in the race, on a lighter
car and a faster track, so their raw median often beats the medium's (51 of 67 races in
2023-2025). `median_lap` sits next to every median so that is visible; comparing compounds
fairly is step 3. A compound name also means different rubber at each race (Pirelli brings three
of C1-C5), so pace by compound is per race, never pooled across races.

Run it over every race in the lake:

    python -m src.analytics.laps --season 2023 2024 2025
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from typing import Any, Dict, Iterable, List, Optional, Sequence

import numpy as np
import pandas as pd

from src.analytics.neutralisations import describe_periods, neutralised_periods
from src.pipeline import lake

OUTLIER_THRESHOLD_SEC = 3.0   # Rohan's note: tyre wear and dirty air explain 1-3 s at most
REFERENCE_WINDOW_LAPS = 5     # the clean lap and up to 2 clean neighbours on each side
MIN_REFERENCE_LAPS = 3        # fewer clean laps than this in the window: no reference

PACE = "pace"
REASON_LAP_1 = "lap 1"
REASON_RED_FLAG = "red flag"
REASON_SAFETY_CAR = "safety car"
REASON_VSC = "VSC"
REASON_YELLOW = "yellow flag"
REASON_OTHER_STATUS = "not green (other)"     # no green status for another reason, e.g. none recorded
REASON_PIT_LAP = "pit lap"                    # in-lap or out-lap under green
REASON_NO_LAP_TIME = "no lap time"            # under green and not a pit lap, yet no time
REASON_INACCURATE = "timing not accurate"     # FastF1 IsAccurate = False
REASON_GENERATED = "generated by FastF1"
REASON_OUTLIER = "outlier"

EXCLUSION_ORDER = (REASON_LAP_1, REASON_RED_FLAG, REASON_SAFETY_CAR, REASON_VSC, REASON_YELLOW,
                   REASON_OTHER_STATUS, REASON_PIT_LAP, REASON_NO_LAP_TIME, REASON_INACCURATE,
                   REASON_GENERATED, REASON_OUTLIER)
CLEAN_LAP_REASONS = EXCLUSION_ORDER[:-1]   # together exactly `not is_clean_lap`

COMPOUND_ORDER = ("SOFT", "MEDIUM", "HARD", "INTERMEDIATE", "WET")

REQUIRED_COLUMNS = (
    "driver_code", "lap_number", "lap_time_sec", "compound", "is_in_lap", "is_pit_lap", "is_lap1",
    "is_green", "is_yellow", "is_sc", "is_vsc", "is_red", "is_accurate", "is_generated", "is_clean_lap",
)

STAT_COLUMNS = ["laps", "median_sec", "q25_sec", "q75_sec", "p05_sec", "p95_sec", "fastest_sec", "median_lap"]


# --- classification ---------------------------------------------------------------

def tyre_runs(laps: pd.DataFrame) -> pd.Series:
    """
    Per driver, which run of laps between pit passages each lap belongs to: 1 until the first
    in-lap (included), 2 from the lap after it, and so on. Every passage splits, a pass-through
    as well: a reference never mixes laps from either side of a trip down the pit lane.

    Expects laps sorted by driver then lap.
    """
    passages_before = laps.groupby("driver_code", sort=False)["is_in_lap"].transform(
        lambda s: s.astype(bool).shift(1, fill_value=False).cumsum())
    return (passages_before + 1).astype("int64")


def _first_reason(laps: pd.DataFrame) -> pd.Series:
    """Why each lap is not a clean lap: the first reason in CLEAN_LAP_REASONS that applies (NA if clean)."""
    flag = lambda col: laps[col].astype(bool).to_numpy()
    conditions = [
        flag("is_lap1"), flag("is_red"), flag("is_sc"), flag("is_vsc"), flag("is_yellow"), ~flag("is_green"),
        flag("is_pit_lap"), laps["lap_time_sec"].isna().to_numpy(), ~flag("is_accurate"), flag("is_generated"),
    ]
    reason = np.select(conditions, CLEAN_LAP_REASONS, default="")
    return pd.Series(reason, index=laps.index, dtype="string").replace("", pd.NA)


def _reference(laps: pd.DataFrame, clean: pd.Series) -> pd.Series:
    """Rolling median of clean laps per driver, tyre run and compound; NaN where there is none."""
    c = laps[clean]
    compound = c["compound"].astype("string").fillna("(no compound)")   # a group label, not data
    rolling = lambda s: s.rolling(REFERENCE_WINDOW_LAPS, center=True, min_periods=MIN_REFERENCE_LAPS).median()
    ref = c.groupby([c["driver_code"], c["tyre_run"], compound], sort=False)["lap_time_sec"].transform(rolling)
    return ref.reindex(laps.index)


def classify_laps(laps: pd.DataFrame, threshold_sec: float = OUTLIER_THRESHOLD_SEC) -> pd.DataFrame:
    """
    Silver laps -> the same laps (none dropped), sorted by driver and lap, with:

      tyre_run            laps between two pit passages, numbered per driver from 1
      reference_sec       rolling median of the clean neighbours (clean laps only, else NaN)
      over_reference_sec  lap time - reference (positive = slower)
      outlier_checked     clean lap that had a reference to be checked against
      is_outlier          more than threshold_sec slower than its reference
      pace_status         'pace' or the first reason it is not (EXCLUSION_ORDER)
      is_pace_lap         pace_status == 'pace'

    Pure function: no file access.
    """
    missing = [c for c in REQUIRED_COLUMNS if c not in laps.columns]
    if missing:
        raise ValueError(f"Silver laps are missing columns needed for pace laps: {missing}")

    df = laps.sort_values(["driver_code", "lap_number"]).reset_index(drop=True)
    df["tyre_run"] = tyre_runs(df)
    reason = _first_reason(df)
    clean = reason.isna().to_numpy()

    disagree = clean != df["is_clean_lap"].astype(bool).to_numpy()
    if disagree.any():
        raise ValueError(f"{int(disagree.sum())} laps: the exclusion reasons and Silver's is_clean_lap disagree. "
                         "If is_clean_lap changed in cleaner.py, change CLEAN_LAP_REASONS to match.")

    df["reference_sec"] = _reference(df, pd.Series(clean, index=df.index))
    df["over_reference_sec"] = df["lap_time_sec"] - df["reference_sec"]
    df["outlier_checked"] = clean & df["reference_sec"].notna().to_numpy()
    df["is_outlier"] = df["outlier_checked"] & (df["over_reference_sec"] > threshold_sec).fillna(False)

    status = reason.copy()
    status[clean] = PACE
    status[df["is_outlier"].to_numpy()] = REASON_OUTLIER
    df["pace_status"] = status
    df["is_pace_lap"] = (status == PACE).to_numpy()
    return df


def pace_laps(classified: pd.DataFrame) -> pd.DataFrame:
    """The laps that show racing pace (pace_status == 'pace')."""
    return classified[classified["is_pace_lap"]]


# --- what was excluded --------------------------------------------------------------

def exclusion_ledger(classified: pd.DataFrame) -> pd.DataFrame:
    """
    Where the laps went, in the order the reasons are applied: one row for all laps, one per
    reason (listed even at 0, so ledgers of different races line up), one for the pace laps.

    Columns: reason, laps (removed at this step), remaining (after it), share (of all laps).
    """
    total = len(classified)
    counts = classified["pace_status"].value_counts()
    share = lambda n: n / total if total else np.nan
    rows = [{"reason": "all laps", "laps": total, "remaining": total, "share": share(total)}]
    remaining = total
    for reason in EXCLUSION_ORDER:
        n = int(counts.get(reason, 0))
        remaining -= n
        rows.append({"reason": reason, "laps": n, "remaining": remaining, "share": share(n)})
    rows.append({"reason": "pace laps", "laps": remaining, "remaining": remaining, "share": share(remaining)})
    return pd.DataFrame(rows, columns=["reason", "laps", "remaining", "share"])


def pace_summary(classified: pd.DataFrame) -> Dict[str, Any]:
    """The headline counts of one race's lap selection."""
    total = len(classified)
    pace = int(classified["is_pace_lap"].sum())
    clean = int(classified["pace_status"].isin([PACE, REASON_OUTLIER]).sum())
    outliers = int(classified["is_outlier"].sum())
    return {
        "laps": total,
        "clean_laps": clean,
        "pace_laps": pace,
        "pace_pct": round(100.0 * pace / total, 1) if total else None,
        "outliers": outliers,
        "outlier_pct_of_clean": round(100.0 * outliers / clean, 2) if clean else None,
        "unchecked": int((classified["is_pace_lap"] & ~classified["outlier_checked"]).sum()),
    }


# --- raw pace by compound -------------------------------------------------------------

def compound_rank(compound) -> int:
    """Sort key: soft, medium, hard, inter, wet, then any other label, then no compound."""
    if not isinstance(compound, str):          # None, NaN or pd.NA: the feed gave no compound
        return len(COMPOUND_ORDER) + 1
    return COMPOUND_ORDER.index(compound) if compound in COMPOUND_ORDER else len(COMPOUND_ORDER)


def _stats(group: pd.DataFrame) -> Dict[str, Any]:
    t = group["lap_time_sec"]
    return {
        "laps": int(len(group)),
        "median_sec": float(t.median()),
        "q25_sec": float(t.quantile(0.25)),
        "q75_sec": float(t.quantile(0.75)),
        "p05_sec": float(t.quantile(0.05)),
        "p95_sec": float(t.quantile(0.95)),
        "fastest_sec": float(t.min()),
        "median_lap": float(group["lap_number"].median()),
    }


def pace_by_compound(classified: pd.DataFrame) -> pd.DataFrame:
    """
    Raw pace of each compound in this race: every driver's pace laps on it. One row per compound
    (null = the feed gave none), soft to wet. NOT fuel-corrected: see the module note.

    Columns: compound, laps, drivers, median / q25 / q75 / p05 / p95 / fastest lap time (s), and
    median_lap, the middle of when that compound was run.
    """
    pace = pace_laps(classified)
    rows = []
    for compound, group in pace.groupby("compound", dropna=False, sort=False):
        compound = None if pd.isna(compound) else str(compound)
        rows.append({"compound": compound, "drivers": int(group["driver_code"].nunique()), **_stats(group)})
    out = pd.DataFrame(rows, columns=["compound", "drivers"] + STAT_COLUMNS)
    order = out["compound"].map(compound_rank)
    return out.assign(_order=order).sort_values("_order").drop(columns="_order").reset_index(drop=True)


def driver_pace_by_compound(classified: pd.DataFrame) -> pd.DataFrame:
    """
    Raw pace of each driver on each compound: one row per driver and compound, fastest median
    first within a compound. Same columns as pace_by_compound, with driver_code and team instead
    of drivers. Raw, like pace_by_compound: two drivers may have run the same compound at
    different points of the race.
    """
    pace = pace_laps(classified)
    rows = []
    for (code, compound), group in pace.groupby(["driver_code", "compound"], dropna=False, sort=False):
        team = group["team"].dropna().iloc[0] if "team" in group.columns and group["team"].notna().any() else None
        rows.append({"driver_code": str(code), "team": team,
                     "compound": None if pd.isna(compound) else str(compound), **_stats(group)})
    out = pd.DataFrame(rows, columns=["driver_code", "team", "compound"] + STAT_COLUMNS)
    order = out["compound"].map(compound_rank)
    out = out.assign(_order=order).sort_values(["_order", "median_sec"]).drop(columns="_order")
    return out.reset_index(drop=True)


# --- one race, ready to show -----------------------------------------------------------

@dataclass
class RacePace:
    """Step 1 for one race: every lap classified, and everything derived from that."""
    laps: pd.DataFrame            # every Silver lap, with its pace_status (classify_laps)
    ledger: pd.DataFrame          # exclusion_ledger
    summary: Dict[str, Any]       # pace_summary
    by_compound: pd.DataFrame     # pace_by_compound
    by_driver: pd.DataFrame       # driver_pace_by_compound
    periods: pd.DataFrame         # neutralised_periods


def race_pace(silver_laps: pd.DataFrame, threshold_sec: float = OUTLIER_THRESHOLD_SEC) -> RacePace:
    """Everything step 1 says about one race, from its Silver laps. Pure function."""
    classified = classify_laps(silver_laps, threshold_sec)
    return RacePace(
        laps=classified,
        ledger=exclusion_ledger(classified),
        summary=pace_summary(classified),
        by_compound=pace_by_compound(classified),
        by_driver=driver_pace_by_compound(classified),
        periods=neutralised_periods(silver_laps),
    )


def load_race_pace(year: int, round_number: int, session: str = "R",
                   root: str = lake.DEFAULT_LAKE_ROOT) -> RacePace:
    """Read one race's Silver laps from the lake and run step 1 on them."""
    path = lake.table_path(lake.SILVER, "laps", year, round_number, session, root)
    if not path.exists():
        raise FileNotFoundError(f"{year} round {round_number}: no Silver laps in the lake ({path}).")
    return race_pace(lake.read_table(path))


# --- every race in the lake ---------------------------------------------------------------

def season_summary(seasons: Iterable[int], root: str = lake.DEFAULT_LAKE_ROOT,
                   threshold_sec: float = OUTLIER_THRESHOLD_SEC) -> pd.DataFrame:
    """One row per race (sessions 'R' of these seasons): step 1's counts and its neutralised periods."""
    wanted = set(int(s) for s in seasons)
    rows: List[Dict[str, Any]] = []
    for path in lake.list_sessions(lake.SILVER, "laps", root):
        if "session=R" not in path.parts:
            continue
        laps = lake.read_table(path)
        if laps.empty or int(laps["season"].iloc[0]) not in wanted:
            continue
        season, round_number = int(laps["season"].iloc[0]), int(laps["round"].iloc[0])
        pace = race_pace(laps, threshold_sec)
        try:
            event = lake.read_manifest(season, round_number, "R", root).get("event_name")
        except FileNotFoundError:
            event = None
        rows.append({"season": season, "round": round_number, "event_name": event, **pace.summary,
                     "periods": describe_periods(pace.periods)})
    return pd.DataFrame(rows).sort_values(["season", "round"]).reset_index(drop=True) if rows else pd.DataFrame()


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Phase 2 step 1 over every race in the lake: pace laps, outliers, "
                                                 "neutralised periods")
    parser.add_argument("--season", type=int, nargs="+", required=True, help="one or more seasons, e.g. 2023 2024")
    parser.add_argument("--threshold", type=float, default=OUTLIER_THRESHOLD_SEC,
                        help=f"outlier threshold in seconds (default {OUTLIER_THRESHOLD_SEC})")
    parser.add_argument("--lake", default=lake.DEFAULT_LAKE_ROOT, help="lake root folder (default: data)")
    args = parser.parse_args(argv)

    table = season_summary(args.season, args.lake, args.threshold)
    if table.empty:
        print("No Silver laps in the lake for these seasons.")
        return 1
    with pd.option_context("display.width", 250, "display.max_rows", 500, "display.max_colwidth", 60):
        print(table.drop(columns=["clean_laps"]).to_string(index=False))
    laps, clean, pace = table["laps"].sum(), table["clean_laps"].sum(), table["pace_laps"].sum()
    outliers, unchecked = table["outliers"].sum(), table["unchecked"].sum()
    print(f"\n{len(table)} races: {laps:,} laps, {clean:,} clean, {pace:,} pace laps ({100 * pace / laps:.1f} %), "
          f"{outliers:,} outliers ({100 * outliers / clean:.2f} % of clean), {unchecked:,} pace laps unchecked")
    report = lake.write_report(table, "pace_laps", args.lake)
    print(f"Report: {report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
